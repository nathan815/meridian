'use strict';
const assert = require('node:assert/strict');
require('./break-preferences.js');
const {model} = require('./break-status.js');
const minute = 60000, start = Date.parse('2026-11-20T09:00:00Z');
const working = {active: true, mode: 'working', punchedInAt: start, workStartedAt: start, lastBreakEndedAt: null};
assert.equal(model(working, start + 49 * minute + 59000).tone, 'working');
assert.equal(model(working, start + 50 * minute).tone, 'nearing');
assert.equal(model(working, start + 12 * minute).detail, '12m · Break due in 48m');
assert.equal(model(working, start + 50 * minute).detail, '50m · Break due in 10m');
assert.equal(model(working, start + 60 * minute).tone, 'overdue');
assert.equal(model(working, start + 60 * minute).detail, '1h · Break due now');
assert.equal(model(working, start + 61 * minute).detail, '1h 1m · Break overdue by 1m');
assert.equal(model({...working, mode: 'break', breakStartedAt: start + 55 * minute, workStartedAt: null}, start + 70 * minute).tone, 'break');
assert.equal(model({active: false}, start + 70 * minute).tone, 'off');
const custom = {intervalMinutes: 45, warningLeadMinutes: 5, soundEnabled: false, sound: 'bell', notificationsEnabled: true};
assert.equal(model(working, start + 39 * minute + 59000, custom).tone, 'working');
assert.equal(model(working, start + 40 * minute, custom).detail, '40m · Break due in 5m');
assert.equal(model(working, start + 45 * minute, custom).detail, '45m · Break due now');
assert.equal(model(working, start + 46 * minute, custom).detail, '46m · Break overdue by 1m');
console.log('Break status boundaries and off/break suppression passed.');
